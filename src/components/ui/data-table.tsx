"use client"

import * as React from "react" // Import React for useState, useEffect, etc.
import {
  ColumnDef,
  flexRender,
  getCoreRowModel,
  getFilteredRowModel, // Added for filtering
  getSortedRowModel,   // Added for sorting
  getPaginationRowModel, // Optional: for pagination if you add it later
  useReactTable,
  ColumnFiltersState, // Added type for column filters
  SortingState,       // Added type for sorting state
  VisibilityState     // Added type for column visibility
} from "@tanstack/react-table"

import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table"

import { DataTableToolbar } from "./data-table-toolbar" // Import the toolbar

interface DataTableProps<TData, TValue> {
  columns: ColumnDef<TData, TValue>[]
  data: TData[]
  // Add these props to allow external control if needed, or manage internally
  // globalFilter?: string; // If you want the parent to control global filter
  // setGlobalFilter?: (filter: string) => void;
  // filterStatus?: string; // If you want the parent to control status filter
  // setFilterStatus?: (status: string) => void;
}

export function DataTable<TData, TValue>({
  columns,
  data,
}: DataTableProps<TData, TValue>) {
  const [sorting, setSorting] = React.useState<SortingState>([])
  const [columnFilters, setColumnFilters] = React.useState<ColumnFiltersState>([])
  const [globalFilter, setGlobalFilter] = React.useState('') // State for global search
  const [columnVisibility, setColumnVisibility] = React.useState<VisibilityState>({})

  const table = useReactTable({
    data,
    columns,
    getCoreRowModel: getCoreRowModel(),
    onSortingChange: setSorting,
    getSortedRowModel: getSortedRowModel(), // Enable sorting
    onColumnFiltersChange: setColumnFilters,
    getFilteredRowModel: getFilteredRowModel(), // Enable general column filtering
    onGlobalFilterChange: setGlobalFilter, // Enable global search
    getGlobalFilteredRowModel: getGlobalFilteredRowModel(), // Enable global search
    onColumnVisibilityChange: setColumnVisibility, // Enable column visibility toggle
    state: {
      sorting,
      columnFilters,
      globalFilter, // Pass global filter state
      columnVisibility, // Pass column visibility state
    },
  })

  return (
    <div className="space-y-4"> {/* Added space-y for toolbar separation */}
      <DataTableToolbar table={table} /> {/* Integrate the toolbar */}
      <div className="rounded-md border">
        <Table>
          <TableHeader>
            {table.getHeaderGroups().map((headerGroup) => (
              <TableRow key={headerGroup.id}>
                {headerGroup.headers.map((header) => {
                  return (
                    <TableHead key={header.id}>
                      {header.isPlaceholder
                        ? null
                        : flexRender(
                            header.column.columnDef.header,
                            header.getContext()
                          )}
                    </TableHead>
                  )
                })}
              </TableRow>
            ))}
          </TableHeader>
          <TableBody>
            {table.getRowModel().rows?.length ? (
              table.getRowModel().rows.map((row) => (
                <TableRow
                  key={row.id}
                  data-state={row.getIsSelected() && "selected"}
                >
                  {row.getVisibleCells().map((cell) => (
                    <TableCell key={cell.id}>
                      {flexRender(cell.column.columnDef.cell, cell.getContext())}
                    </TableCell>
                  ))}
                </TableRow>
              ))
            ) : (
              <TableRow>
                <TableCell colSpan={columns.length} className="h-24 text-center">
                  No results.
                </TableCell>
              </TableRow>
            )}
          </TableBody>
        </Table>
      </div>
      {/* Optional: Add pagination controls here if you enable getPaginationRowModel */}
      {/* <div className="flex items-center justify-end space-x-2 py-4">
        <Button
          variant="outline"
          size="sm"
          onClick={() => table.previousPage()}
          disabled={!table.getCanPreviousPage()}
        >
          Previous
        </Button>
        <Button
          variant="outline"
          size="sm"
          onClick={() => table.nextPage()}
          disabled={!table.getCanNextPage()}
        >
          Next
        </Button>
      </div> */}
    </div>
  )
}